#!/usr/bin/env python3
"""Generate rules/diet_vocab.json and rules/diet_coverage.md from the product data.

    python3 build_diet_vocab.py

Everything in diet_vocab.json is derived from the data. The only fixed knowledge here is
two small reference tables taken from standards: the GS1 claim grammar (a claim code is a
type prefix + an element, e.g. FREE_FROM + LACTOSE) and the claim element -> INFOODS
nutrient id mapping. Re-run whenever the product file changes; then review
rules/diet_coverage.md and move accepted proposals into rules/diet_overrides.json.
"""
from __future__ import annotations

import collections
import datetime as dt
import json
import os

import catalog

PREFIXES = ["FREE_FROM_", "NO_ADDED_", "LOW_", "HIGH_"]  # GS1 claim type; no prefix = diet type (VEGAN ...)
ELEMENT_NUTRIENT = {"LACTOSE": "LACS", "FAT": "FAT", "SODIUM_SALT": "SALTEQ", "FIBRE": "FIBTG",
                    "PROTEIN": "PRO-", "SUGARS": "SUGAR-"}  # INFOODS tagnames used in nutritionFact
MIN_SAMPLE = 300  # suggest contradictions only from this many claimed products (and common allergens)
MAX_RATIO = 0.1   # an allergen at most 10 % as frequent under the claim as in the whole catalogue


def parse_claim(code):
    for p in PREFIXES:
        if code.startswith(p):
            return p[:-1], code[len(p):]
    return "DIET", code


def default_label(ctype, element):
    e = element.lower().replace("_", " ")
    return {"FREE_FROM": f"free from {e}", "LOW": f"low {e}", "HIGH": f"high {e}",
            "NO_ADDED": f"no added {e}"}.get(ctype, e)


def build_vocab(idx):
    n = len(idx)
    claim_count = collections.Counter(c for p in idx for c in p["claims"])
    base = collections.Counter(a for p in idx for a in p["allergens"])
    parsed = {c: parse_claim(c) for c in claim_count}
    by_element = collections.defaultdict(dict)
    for c, (t, e) in parsed.items():
        by_element[e][t] = c
    codes = {}
    for c in sorted(claim_count):
        t, e = parsed[c]
        entry = {"kind": "claim", "type": t, "element": e, "label": default_label(t, e), "products": claim_count[c]}
        if e in ELEMENT_NUTRIENT:
            entry["nutrient"] = ELEMENT_NUTRIENT[e]
        if t == "LOW" and "FREE_FROM" in by_element[e]:
            entry["satisfied_by"] = [by_element[e]["FREE_FROM"]]  # free-from X satisfies low X
        if t == "FREE_FROM" and "LOW" in by_element[e]:
            entry["near_miss"] = [by_element[e]["LOW"]]           # low X is NOT free-from X
        if t in ("FREE_FROM", "DIET"):
            if claim_count[c] >= MIN_SAMPLE:
                ps = [p for p in idx if c in p["claims"]]
                cnt = collections.Counter(a for p in ps for a in p["allergens"])
                ratios = sorted(((cnt[a] / len(ps)) / (base[a] / n), a) for a in base if base[a] >= MIN_SAMPLE)
                entry["suggested_contradictions"] = [{"allergen": a, "ratio": round(r, 3)}
                                                     for r, a in ratios if r <= MAX_RATIO]
            else:
                entry["suggested_contradictions_note"] = f"only {claim_count[c]} products: sample too small"
        codes[c] = entry
    return {
        "_doc": "GENERATED by build_diet_vocab.py from the product data. Do not edit by hand: "
                "synonyms go in diet_terms.json, policy in diet_overrides.json.",
        "generated_at": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "catalog_size": n,
        "codes": codes,
        "allergen_counts": {
            "CONTAINS": dict(base.most_common()),
            "MAY_CONTAIN": dict(collections.Counter(a for p in idx for a in p["allergens_may_contain"]).most_common()),
            "nonAllergen_FREE_FROM": dict(collections.Counter(a for p in idx for a in p["free_from"]).most_common()),
        },
    }


def coverage_report(idx, vocab, rules):
    L = ["# Diet rule coverage", "",
         f"Generated {vocab['generated_at']} from {vocab['catalog_size']} products by `build_diet_vocab.py`.", "",
         "Each rule is run on every product. *Strong* = structured evidence without contradiction; "
         "*conflict* = structured evidence contradicted by another source (sent to a person); "
         "*name only* = weak evidence (sent to a person). Rules with reviewed = no can be searched, "
         "but an order that relies on them always needs a person.", "",
         "| code | label | reviewed | GS1 claims | strong | conflict | name only | look-alike | buyer terms | "
         "suggested contradictions (ratio) | policy contradictions |",
         "|---|---|---|---:|---:|---:|---:|---:|---:|---|---|"]
    for code, r in sorted(rules.items(), key=lambda kv: -kv[1]["products"]):
        stat = collections.Counter()
        for p in idx:
            status, ev, strength = catalog.diet_evidence(p, code, rules)
            if status == "pass":
                stat["conflict" if ev.startswith("CONFLICT") else "strong" if strength >= 1.0 else "name"] += 1
            elif status in ("near_miss", "contradicted"):
                stat["near"] += 1
        v = vocab["codes"].get(code, {})
        sugg = ", ".join(f"{s['allergen']} {s['ratio']:g}" for s in v.get("suggested_contradictions", [])) \
            or v.get("suggested_contradictions_note", "–")
        pol = ", ".join(r["contradict_allergens"]) + (" (+MAY_CONTAIN)" if r["contradict_may_contain"] else "")
        L.append(f"| `{code}` | {r['label']} | {'yes' if r['reviewed'] else 'no'} | {r['products']} | "
                 f"{stat['strong']} | {stat['conflict']} | {stat['name']} | {stat['near']} | "
                 f"{len(r['request_terms'])} | {sugg} | {pol or '–'} |")
    L += ["", "Ratio = how often the allergen is listed as CONTAINS under the claim, relative to the whole "
          "catalogue (0 = never). A low ratio suggests the allergen contradicts the claim; a person decides "
          "whether to copy it into `diet_overrides.json`."]
    return "\n".join(L) + "\n"


def main():
    idx = catalog.load_index()
    vocab = build_vocab(idx)
    os.makedirs(catalog.RULES_DIR, exist_ok=True)
    with open(os.path.join(catalog.RULES_DIR, "diet_vocab.json"), "w", encoding="utf-8") as f:
        json.dump(vocab, f, ensure_ascii=False, indent=1)
    rules = catalog.build_diet_rules(vocab, catalog._read_rules_file("diet_terms.json", {}),
                                     catalog._read_rules_file("diet_overrides.json", {"codes": {}}))
    with open(os.path.join(catalog.RULES_DIR, "diet_coverage.md"), "w", encoding="utf-8") as f:
        f.write(coverage_report(idx, vocab, rules))
    reviewed = sum(r["reviewed"] for r in rules.values())
    print(f"{len(vocab['codes'])} claim codes from {vocab['catalog_size']} products -> {len(rules)} rules "
          f"({reviewed} reviewed). Wrote rules/diet_vocab.json and rules/diet_coverage.md")


if __name__ == "__main__":
    main()
